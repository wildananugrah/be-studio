package com.mhamzah.gateway.audit;

import java.util.ArrayList;
import java.util.List;
import liquibase.change.custom.CustomSqlChange;
import liquibase.database.Database;
import liquibase.database.core.OracleDatabase;
import liquibase.database.core.PostgresDatabase;
import liquibase.exception.ValidationErrors;
import liquibase.resource.ResourceAccessor;
import liquibase.statement.SqlStatement;
import liquibase.statement.core.RawSqlStatement;

/**
 * Liquibase change (015-audit-partitioning) that drops the audit tables and creates them again partitioned by time.
 * The rows they held are dropped. {@code gw_audit_transaction} is partitioned by {@code started_at};
 * {@code gw_audit_step} carries its transaction's start time ({@code transaction_started_at}) and is partitioned by
 * it, so a transaction and its steps always sit in partitions covering the same period and are dropped together.
 * The primary keys include the partition column, and the step's link to its transaction is no longer a foreign key.
 * <ul>
 *   <li>PostgreSQL: declarative {@code PARTITION BY RANGE}. The partitions themselves are created by
 *   {@link AuditPartitions} (ahead of time, and on demand when a row finds none).</li>
 *   <li>Oracle: {@code INTERVAL} partitioning, which creates partitions as rows arrive; the interval is set from
 *   {@code gateway.audit.partition.interval} at startup. Needs the Oracle Partitioning option.</li>
 * </ul>
 * Plain SQL is generated, so {@code liquibase updateSQL} shows it for DBAs.
 */
public class AuditPartitionDdl implements CustomSqlChange {

    private String transactionTable;
    private String stepTable;

    public void setTransactionTable(String transactionTable) {
        this.transactionTable = transactionTable;
    }

    public void setStepTable(String stepTable) {
        this.stepTable = stepTable;
    }

    @Override
    public SqlStatement[] generateStatements(Database database) {
        String schema = database.getDefaultSchemaName();
        String tx = qualify(schema, transactionTable);
        String step = qualify(schema, stepTable);
        List<String> sql = new ArrayList<>();
        if (database instanceof OracleDatabase) {
            sql.add("DROP TABLE " + step + " CASCADE CONSTRAINTS PURGE");
            sql.add("DROP TABLE " + tx + " CASCADE CONSTRAINTS PURGE");
            sql.add("CREATE TABLE " + tx + " ("
                    + "id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL, "
                    + "correlation_id VARCHAR2(64) NOT NULL, flow_code VARCHAR2(100), http_method VARCHAR2(10), "
                    + "path VARCHAR2(1000), client_status NUMBER(10), error_type VARCHAR2(50), error_code VARCHAR2(100), "
                    + "request_payload CLOB, response_payload CLOB, started_at TIMESTAMP NOT NULL, duration_ms NUMBER(19), "
                    + "request_headers CLOB, response_headers CLOB, "
                    + "CONSTRAINT " + transactionTable + "_PK PRIMARY KEY (id, started_at) USING INDEX LOCAL) "
                    + oraclePartitioning("started_at"));
            sql.add("CREATE INDEX " + qualify(schema, transactionTable + "_IX1") + " ON " + tx + " (correlation_id) LOCAL");
            sql.add("CREATE INDEX " + qualify(schema, transactionTable + "_IX2") + " ON " + tx + " (started_at) LOCAL");
            sql.add("CREATE TABLE " + step + " ("
                    + "id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL, "
                    + "transaction_id NUMBER(19) NOT NULL, transaction_started_at TIMESTAMP NOT NULL, "
                    + "step_name VARCHAR2(100), target_system VARCHAR2(100), http_method VARCHAR2(10), url VARCHAR2(2000), "
                    + "http_status NUMBER(10), outcome VARCHAR2(10), request_payload CLOB, response_payload CLOB, "
                    + "started_at TIMESTAMP, duration_ms NUMBER(19), request_headers CLOB, response_headers CLOB, "
                    + "CONSTRAINT " + stepTable + "_PK PRIMARY KEY (id, transaction_started_at) USING INDEX LOCAL) "
                    + oraclePartitioning("transaction_started_at"));
            sql.add("CREATE INDEX " + qualify(schema, stepTable + "_IX1") + " ON " + step + " (transaction_id) LOCAL");
        } else if (database instanceof PostgresDatabase) {
            String txSeq = qualify(schema, transactionTable + "_SEQ");
            String stepSeq = qualify(schema, stepTable + "_SEQ");
            sql.add("DROP TABLE IF EXISTS " + step);
            sql.add("DROP TABLE IF EXISTS " + tx);
            sql.add("CREATE SEQUENCE IF NOT EXISTS " + txSeq);
            sql.add("CREATE SEQUENCE IF NOT EXISTS " + stepSeq);
            sql.add("CREATE TABLE " + tx + " ("
                    + "id BIGINT NOT NULL DEFAULT nextval('" + txSeq + "'), "
                    + "correlation_id VARCHAR(64) NOT NULL, flow_code VARCHAR(100), http_method VARCHAR(10), "
                    + "path VARCHAR(1000), client_status INTEGER, error_type VARCHAR(50), error_code VARCHAR(100), "
                    + "request_payload TEXT, response_payload TEXT, started_at TIMESTAMP NOT NULL, duration_ms BIGINT, "
                    + "request_headers TEXT, response_headers TEXT, "
                    + "CONSTRAINT " + transactionTable + "_PK PRIMARY KEY (id, started_at)) "
                    + "PARTITION BY RANGE (started_at)");
            sql.add("CREATE INDEX " + transactionTable + "_IX1 ON " + tx + " (correlation_id)");
            sql.add("CREATE INDEX " + transactionTable + "_IX2 ON " + tx + " (started_at)");
            sql.add("ALTER SEQUENCE " + txSeq + " OWNED BY " + tx + ".id");
            sql.add("CREATE TABLE " + step + " ("
                    + "id BIGINT NOT NULL DEFAULT nextval('" + stepSeq + "'), "
                    + "transaction_id BIGINT NOT NULL, transaction_started_at TIMESTAMP NOT NULL, "
                    + "step_name VARCHAR(100), target_system VARCHAR(100), http_method VARCHAR(10), url VARCHAR(2000), "
                    + "http_status INTEGER, outcome VARCHAR(10), request_payload TEXT, response_payload TEXT, "
                    + "started_at TIMESTAMP, duration_ms BIGINT, request_headers TEXT, response_headers TEXT, "
                    + "CONSTRAINT " + stepTable + "_PK PRIMARY KEY (id, transaction_started_at)) "
                    + "PARTITION BY RANGE (transaction_started_at)");
            sql.add("CREATE INDEX " + stepTable + "_IX1 ON " + step + " (transaction_id)");
            sql.add("ALTER SEQUENCE " + stepSeq + " OWNED BY " + step + ".id");
        } else {
            throw new IllegalStateException("Audit partitioning supports PostgreSQL and Oracle, not "
                    + database.getShortName());
        }
        return sql.stream().map(RawSqlStatement::new).toArray(SqlStatement[]::new);
    }

    /** Monthly to start with; {@link AuditPartitions} switches it to the configured interval at startup. */
    private static String oraclePartitioning(String column) {
        return "PARTITION BY RANGE (" + column + ") INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) "
                + "(PARTITION p_first VALUES LESS THAN (TIMESTAMP '2000-01-01 00:00:00'))";
    }

    private static String qualify(String schema, String name) {
        return schema == null || schema.isBlank() ? name : schema + "." + name;
    }

    @Override
    public String getConfirmationMessage() {
        return "Audit tables " + transactionTable + " and " + stepTable + " re-created partitioned";
    }

    @Override
    public void setUp() {}

    @Override
    public void setFileOpener(ResourceAccessor resourceAccessor) {}

    @Override
    public ValidationErrors validate(Database database) {
        ValidationErrors errors = new ValidationErrors();
        errors.checkRequiredField("transactionTable", transactionTable);
        errors.checkRequiredField("stepTable", stepTable);
        return errors;
    }
}
